// Запускается с playwright 1.56.1 в одноразовом стенде scripts/integration-npm.mjs.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const base = process.env.TEST_GATEWAY_URL;
  const login = await page.request.post(base + '/api/tokens', { data: { identity: 'compat@example.test', secret: 'Disposable-Compat-Only-2026' } });
  const auth = await login.json(); assert.ok(auth.token);
  await page.goto(base);
  await page.evaluate(auth => localStorage.setItem('authentications', JSON.stringify([auth])), auth);
  await page.goto(base + '/nginx/proxy');
  await page.locator('[data-cf-cell]').first().waitFor();
  assert.equal(await page.locator('[data-cf-header]').count(), 1);
  assert.equal(await page.locator('[data-cf-cell] button').count(), 3);
  await page.locator('.cf-sync').click();
  await page.locator('.cf-sync[aria-pressed="true"]').waitFor();
  await page.locator('.cf-cloud').click();
  await page.locator('.cf-cloud[aria-pressed="false"]').waitFor();
  await page.locator('thead th').nth(1).click();
  assert.equal(await page.locator('[data-cf-cell]').count(), 1);
  await page.locator('.cf-sync').focus();
  await page.locator('#cf-dns-tooltip:not([hidden])').waitFor();
  await page.keyboard.press('Escape');
  assert.ok(await page.locator('#cf-dns-tooltip').isHidden());
  await page.screenshot({ path: '/work/desktop-proxy.png' });
  // Воспроизводим повторное использование DOM строки React с неизвестным доменом.
  await page.locator('tbody .domain-name').first().evaluate(el => { el.textContent = 'unknown.example.test'; });
  await page.locator('[data-cf-cell]').waitFor({ state: 'detached' });
  await page.reload(); await page.locator('[data-cf-cell]').waitFor();
  await page.goto(base + '/settings');
  await page.locator('#cf-dns-tab').click();
  await page.locator('input[name=externalIPv4]').fill('1.1.1.1');
  await page.locator('#cf-dns-settings button[type=submit]').click();
  await page.getByText('Настройки Cloudflare обновлены').waitFor();
  await page.locator('#cf-dns-default-tab').click();
  assert.ok(await page.locator('#cf-dns-panel').isHidden());
  await page.locator('#cf-dns-default-tab').press('ArrowDown');
  assert.ok(await page.locator('#cf-dns-panel').isVisible());
  await page.screenshot({ path: '/work/desktop-settings.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/work/mobile-settings.png' });
  assert.ok(await page.locator('input[name=externalIPv4]').isVisible());
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false);
  await page.goto(base + '/nginx/proxy'); await page.locator('[data-cf-cell]').waitFor();
  await page.locator('[data-cf-cell]').evaluate(el => el.scrollIntoView());
  await page.screenshot({ path: '/work/mobile-proxy.png' });
  page.once('dialog', dialog => dialog.dismiss()); await page.locator('.cf-delete').click();
  assert.equal(await page.locator('.cf-sync').getAttribute('aria-pressed'), 'true');
  page.once('dialog', dialog => dialog.accept()); await page.locator('.cf-delete').click();
  await page.locator('.cf-sync[aria-pressed="false"]').waitFor();
  assert.deepEqual(errors, []);
  await browser.close(); console.log('PASS: desktop/mobile, Settings/save/tabs/keyboard, Sync/Proxy/delete, sorting, tooltip/Escape, stale row removal');
})().catch(e => { console.error(e); process.exit(1); });
